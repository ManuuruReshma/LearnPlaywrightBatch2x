// 09_VSCode_Shortcuts_Windows.js
// All Important VS Code Shortcuts for Windows

/*
GENERAL SHORTCUTS
=================
*/

// Ctrl + Shift + P        => Open Command Palette
// Ctrl + ,                => Open Settings
// Ctrl + K + S            => Open Keyboard Shortcuts
// Ctrl + `                => Open Integrated Terminal
// Ctrl + J                => Toggle Panel
// Ctrl + B                => Toggle Sidebar
// Ctrl + Shift + E        => Open Explorer
// Ctrl + Shift + F        => Open Find in Files
// Ctrl + Shift + D        => Open Debug
// Ctrl + Shift + X        => Open Extensions
// Ctrl + Shift + G        => Open Source Control (Git)

/*
FILE OPERATIONS
===============
*/

// Ctrl + N                => New File
// Ctrl + O                => Open File
// Ctrl + S                => Save File
// Ctrl + Shift + S        => Save As
// Ctrl + W                => Close File
// Ctrl + Shift + W        => Close All Files
// Ctrl + Tab              => Switch Between Open Files
// Ctrl + Shift + Tab      => Switch Files (Reverse)

/*
EDITING SHORTCUTS
=================
*/

// Ctrl + Z                => Undo
// Ctrl + Shift + Z        => Redo
// Ctrl + X                => Cut Line
// Ctrl + C                => Copy Line
// Ctrl + V                => Paste
// Ctrl + Shift + K        => Delete Line
// Ctrl + Enter            => Insert Line Below
// Ctrl + Shift + Enter    => Insert Line Above
// Alt + Up                => Move Line Up
// Alt + Down              => Move Line Down
// Ctrl + D                => Select Word (Add to selection)
// Ctrl + L                => Select Line
// Ctrl + A                => Select All

/*
NAVIGATION SHORTCUTS
====================
*/

// Ctrl + G                => Go to Line
// Ctrl + F                => Find
// Ctrl + H                => Find and Replace
// F3                      => Find Next
// Shift + F3              => Find Previous
// Alt + Enter             => Replace All
// Ctrl + Shift + L        => Select All Occurrences
// Ctrl + Home             => Go to Beginning of File
// Ctrl + End              => Go to End of File
// Ctrl + /                => Toggle Line Comment
// Shift + Alt + A         => Toggle Block Comment

/*
CODE FORMATTING
===============
*/

// Ctrl + Shift + I        => Format Document
// Ctrl + K + F            => Format Selection
// Tab                     => Indent
// Shift + Tab             => Outdent

/*
DEBUGGING
=========
*/

// F5                      => Start Debugging
// Ctrl + F5               => Start Without Debugging
// F9                      => Toggle Breakpoint
// F10                     => Step Over
// F11                     => Step Into
// Shift + F11             => Step Out

/*
EDITOR MANAGEMENT
=================
*/

// Ctrl + \                => Split Editor
// Ctrl + 1                => Focus First Editor
// Ctrl + 2                => Focus Second Editor
// Ctrl + 3                => Focus Third Editor
// Ctrl + K + Right        => Next Editor Group
// Ctrl + K + Left         => Previous Editor Group
// Ctrl + Alt + Right      => Move Editor to Right Group
// Ctrl + Alt + Left       => Move Editor to Left Group

/*
USEFUL COMMANDS
===============
*/

// Ctrl + Shift + `        => Create New Terminal
// Ctrl + Shift + C        => Open Command Prompt (in folder)
// Alt + Z                 => Toggle Word Wrap
// F11                     => Toggle Full Screen
// F1                      => Open Help/Command Palette

// Tips for Windows:
// - Use Ctrl for most shortcuts
// - Use Shift for extending selections
// - Use Alt for alternative actions
// - Customize shortcuts in File > Preferences > Keyboard Shortcuts
