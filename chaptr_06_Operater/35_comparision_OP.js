
//>,<,>=,<=,==,===,!=,!==,!==,

//=-> assignment operator
//==-> comparison operator (value)
//===-> comparison operator (value and type)

console.log(10 > 5); //true
console.log(10 < 5); //false
console.log(10 >= 10); //true
console.log(10 <= 9); //false
console.log(10 == '10'); //true (value is equal, but type is different)
console.log(10 === '10'); //false (value is equal, but type is different)   
console.log(10 != '10'); //false (value is equal, but type is different)
console.log(10 !== '10'); //true (value is equal, but type is different)
console.log(10 !== 10); //false (value and type are equal)


